"""
Sleep/Skill Linkage: Connect SleepLoop MTS summaries with SkillEvolutionLoop.

This module provides the connection between:
- SleepLoop's consolidated MTS (Mid-Term Store) summaries
- SkillEvolutionLoop's generate_skills_from_traces method

The linkage allows skill mining to leverage consolidated knowledge from sleep cycles.
"""
from __future__ import annotations

from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Any, Dict, List, Optional
import json
import logging
from quentin.utils.time import now_iso

logger = logging.getLogger(__name__)


@dataclass
class MTSSummary:
    """
    Mid-Term Store summary tagged for skill mining.

    These summaries are generated by SleepLoop during consolidation
    and consumed by SkillEvolutionLoop for skill extraction.

    Fields:
    - summary_id: Unique identifier
    - summary_text: Consolidated knowledge summary
    - source_trace_ids: Trace IDs that contributed to this summary
    - domain: Domain this summary relates to
    - patterns: Extracted patterns (key-value pairs)
    - tagged_for_skill_mining: Whether this summary is marked for skill mining
    - created_at: When summary was created
    - metadata: Additional context
    """
    summary_id: str
    summary_text: str
    source_trace_ids: List[str]
    domain: str = "general"
    patterns: Dict[str, Any] = None
    tagged_for_skill_mining: bool = True
    created_at: str = ""
    metadata: Dict[str, Any] = None

    def __post_init__(self):
        if self.patterns is None:
            self.patterns = {}
        if self.metadata is None:
            self.metadata = {}
        if not self.created_at:
            self.created_at = now_iso()

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @staticmethod
    def from_dict(data: Dict[str, Any]) -> "MTSSummary":
        return MTSSummary(
            summary_id=data["summary_id"],
            summary_text=data["summary_text"],
            source_trace_ids=data.get("source_trace_ids", []),
            domain=data.get("domain", "general"),
            patterns=data.get("patterns", {}),
            tagged_for_skill_mining=data.get("tagged_for_skill_mining", True),
            created_at=data.get("created_at", now_iso()),
            metadata=data.get("metadata", {}),
        )


class SleepSkillLinkage:
    """
    Linkage between SleepLoop and SkillEvolutionLoop.

    Responsibilities:
    - Store MTS summaries from SleepLoop
    - Provide summaries to SkillEvolutionLoop for skill mining
    - Track which summaries have been processed
    """

    def __init__(
        self,
        *,
        repo_root: str | Path = ".",
        storage_path: Optional[str | Path] = None,
    ):
        """
        Initialize linkage storage.

        Args:
            repo_root: Repository root directory
            storage_path: Optional custom storage path for MTS summaries
        """
        self.repo_root = Path(repo_root).resolve()

        if storage_path is None:
            self.storage_path = self.repo_root / "data" / "mts" / "summaries.jsonl"
        else:
            self.storage_path = Path(storage_path)

        self.storage_path.parent.mkdir(parents=True, exist_ok=True)
        self._processed_path = self.storage_path.with_name("processed_summaries.jsonl")

    def _load_processed_ids(self) -> set[str]:
        if not self._processed_path.exists():
            return set()
        processed: set[str] = set()
        try:
            with self._processed_path.open("r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        d = json.loads(line)
                        sid = str(d.get("summary_id") or "").strip()
                        if sid:
                            processed.add(sid)
                    except Exception:
                        continue
        except Exception:
            logger.exception("Failed to load processed summary ids")
        return processed

    def mark_processed(self, summary_id: str, *, notes: str = "") -> None:
        summary_id = str(summary_id or "").strip()
        if not summary_id:
            return
        self._processed_path.parent.mkdir(parents=True, exist_ok=True)
        try:
            with self._processed_path.open("a", encoding="utf-8") as f:
                f.write(
                    json.dumps(
                        {
                            "summary_id": summary_id,
                            "notes": notes,
                            "processed_at": now_iso(),
                        },
                        ensure_ascii=False,
                    )
                    + "\n"
                )
        except Exception:
            logger.exception("Failed to mark summary processed")

    def emit_mts_summary(
        self,
        summary: MTSSummary,
    ) -> None:
        """
        Emit an MTS summary from SleepLoop.

        Args:
            summary: MTSSummary to store
        """
        try:
            with self.storage_path.open("a", encoding="utf-8") as f:
                f.write(json.dumps(summary.to_dict(), ensure_ascii=False) + "\n")

            logger.info(
                f"Emitted MTS summary {summary.summary_id} "
                f"(domain={summary.domain}, tagged={summary.tagged_for_skill_mining})"
            )
        except Exception:
            logger.exception("Failed to emit MTS summary")

    def fetch_summaries_for_skill_mining(
        self,
        *,
        domain: Optional[str] = None,
        limit: Optional[int] = None,
        only_unprocessed: bool = False,
    ) -> List[MTSSummary]:
        """
        Fetch MTS summaries for skill mining.

        Args:
            domain: Optional domain filter
            limit: Maximum number of summaries to return
            only_unprocessed: Only return summaries not yet processed

        Returns:
            List of MTSSummary objects
        """
        if not self.storage_path.exists():
            logger.info("No MTS summaries available")
            return []

        summaries = []
        processed_ids: set[str] = set()
        if only_unprocessed:
            processed_ids = self._load_processed_ids()

        try:
            with self.storage_path.open("r", encoding="utf-8") as f:
                for line in f:
                    try:
                        data = json.loads(line.strip())
                        summary = MTSSummary.from_dict(data)

                        # Apply filters
                        if not summary.tagged_for_skill_mining:
                            continue

                        if domain and summary.domain != domain:
                            continue

                        if only_unprocessed and summary.summary_id in processed_ids:
                            continue

                        summaries.append(summary)

                    except Exception:
                        logger.exception("Failed to parse MTS summary")

            # Apply limit
            if limit:
                summaries = summaries[-limit:]

            logger.info(
                f"Fetched {len(summaries)} MTS summaries for skill mining "
                f"(domain={domain}, limit={limit})"
            )

            return summaries

        except Exception:
            logger.exception("Failed to fetch MTS summaries")
            return []

    def log_skill_mining_consumption(
        self,
        summary_id: str,
        skills_generated: int,
        notes: str = "",
    ) -> None:
        """
        Log that a summary was consumed for skill mining.

        Args:
            summary_id: Summary that was processed
            skills_generated: Number of skills generated from this summary
            notes: Additional notes
        """
        log_path = self.repo_root / "data" / "mts" / "consumption_log.jsonl"
        log_path.parent.mkdir(parents=True, exist_ok=True)

        log_entry = {
            "summary_id": summary_id,
            "skills_generated": skills_generated,
            "notes": notes,
            "consumed_at": now_iso(),
        }

        try:
            with log_path.open("a", encoding="utf-8") as f:
                f.write(json.dumps(log_entry, ensure_ascii=False) + "\n")

            logger.debug(
                f"Logged consumption of summary {summary_id} "
                f"({skills_generated} skills generated)"
            )
            self.mark_processed(summary_id, notes=f"skills_generated={skills_generated} {notes}".strip())
        except Exception:
            logger.exception("Failed to log skill mining consumption")

    def get_statistics(self) -> Dict[str, Any]:
        """
        Get statistics about MTS summaries and consumption.

        Returns:
            Dict with summary and consumption stats
        """
        if not self.storage_path.exists():
            return {
                "total_summaries": 0,
                "tagged_for_mining": 0,
                "domains": [],
            }

        summaries = []
        domains = set()

        try:
            with self.storage_path.open("r", encoding="utf-8") as f:
                for line in f:
                    try:
                        data = json.loads(line.strip())
                        summary = MTSSummary.from_dict(data)
                        summaries.append(summary)
                        domains.add(summary.domain)
                    except Exception:
                        pass

            tagged = sum(1 for s in summaries if s.tagged_for_skill_mining)

            return {
                "total_summaries": len(summaries),
                "tagged_for_mining": tagged,
                "domains": sorted(list(domains)),
            }

        except Exception:
            logger.exception("Failed to get statistics")
            return {
                "total_summaries": 0,
                "tagged_for_mining": 0,
                "domains": [],
            }


# Helper function for use in SkillEvolutionLoop.generate_skills_from_traces
def fetch_mts_summaries_for_mining(
    repo_root: str | Path = ".",
    domain: Optional[str] = None,
    limit: int = 10,
) -> List[MTSSummary]:
    """
    Convenience function to fetch MTS summaries for skill mining.

    This can be called from SkillEvolutionLoop.generate_skills_from_traces
    to access consolidated knowledge from sleep cycles.

    Args:
        repo_root: Repository root
        domain: Optional domain filter
        limit: Max summaries to fetch

    Returns:
        List of MTSSummary objects

    Example:
        ```python
        # In SkillEvolutionLoop.generate_skills_from_traces
        from quentin.evolution.sleep_skill_linkage import fetch_mts_summaries_for_mining

        summaries = fetch_mts_summaries_for_mining(
            repo_root=self.repo_root,
            domain="core",
            limit=10,
        )

        # Use summaries to enhance skill extraction
        for summary in summaries:
            logger.info(f"Using MTS summary: {summary.summary_text[:100]}...")
            # Extract patterns and generate skills
        ```
    """
    linkage = SleepSkillLinkage(repo_root=repo_root)
    return linkage.fetch_summaries_for_skill_mining(domain=domain, limit=limit)
