from __future__ import annotations
from typing import Dict, Any, List
from quentin.analytics.outcome_metrics import OutcomeMetrics

class ROIEstimator:
    """
    P11-D: ROI Estimator
    Calculates business value generated by autonomous operations.
    """
    def estimate_roi(self, metrics: OutcomeMetrics) -> Dict[str, Any]:
        # Simple heuristic: $50/hour saved + direct cost reduction
        value_generated = (metrics.time_saved_hours * 50.0) + metrics.cost_reduction_usd
        
        # Assume system cost is proportional to activity
        system_cost = metrics.activity_count * 0.05 # $0.05 per task
        
        net_gain = value_generated - system_cost
        roi_multiplier = value_generated / system_cost if system_cost > 0 else 0.0
        
        return {
            "domain": metrics.domain,
            "value_generated_usd": value_generated,
            "system_cost_usd": system_cost,
            "net_gain_usd": net_gain,
            "roi_multiplier": roi_multiplier,
            "efficiency_gain": metrics.success_rate * metrics.time_saved_hours
        }
