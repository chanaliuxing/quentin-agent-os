from __future__ import annotations

from dataclasses import dataclass, asdict, is_dataclass
from typing import Any, Dict, List, Optional
import json
import logging
import time
import uuid

from quentin.orchestrator.council import MultiModelCouncil

logger = logging.getLogger(__name__)


class LanguageModel:
    """
    通用 LLM 接口抽象。
    """
    def generate(self, messages: List[Dict[str, str]], **kwargs: Any) -> str:
        raise RuntimeError("LanguageModel is an interface; pass a concrete LLM implementation.")


@dataclass
class OrchestratorConfig:
    """
    控制 orchestrator 内部行为的简单配置。
    """
    enable_reflection: bool = True


@dataclass
class OrchestratorStep:
    step_id: str
    step_type: str            # "plan" | "execute" | "council" | "reflect"
    llm_name: Optional[str]
    description: str
    prompt: Optional[str]
    raw_output: Any
    parsed: Optional[Dict[str, Any]]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class OrchestratorResult:
    trace_id: str
    status: str
    steps: List[OrchestratorStep]
    execution_summary: Dict[str, Any]
    lessons_learned: Optional[Any]
    top_level_metrics: Dict[str, Any]
    final_output: Any

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        # steps 也转 dict
        d["steps"] = [s.to_dict() for s in self.steps]
        return d


class SimpleOrchestrator:
    """
    通用版 Orchestrator：

    - 不依赖具体 domain（Desktop/Legal/Trading 等都可以用）
    - 只需要一个 LLM（主模型） + 可选的 MultiModelCouncil
    - 负责在一次任务内完成：
        1. 规划（plan）
        2. 执行（generate answer / plan-of-steps）
        3. 多模型开会（council）
        4. 自我反思（reflection）

    输出结构直接喂给 RuntimeFacade._build_trace_from_orchestrator。
    """

    def __init__(
        self,
        *,
        llm: Any,
        council: Optional[MultiModelCouncil] = None,
        name: str = "simple-orchestrator",
        config: Optional[OrchestratorConfig] = None,
    ) -> None:
        self.llm = llm
        self.council = council
        self.name = name
        self.config = config or OrchestratorConfig()

    # --------------------------------------------------
    # 对外主接口：执行一次任务
    # --------------------------------------------------
    def run_task(
        self,
        goal: str = None, # Goal can be passed as positional or keyword
        context: Dict[str, Any] = None,
        runtime: Optional[Any] = None,
        # Support signature with 'request' object for compatibility if called via old interface
        request: Any = None,
    ) -> OrchestratorResult:
        """
        RuntimeFacade 会调用这个方法。

        - goal: 用户任务目标（自然语言）
        - context: 附加上下文（domain, user_profile, task_id 等）
        - runtime: 运行时（可以访问 memory_fabric / tools 等）
        """
        # Handle compatibility with (request=...) signature if goal is missing
        if goal is None and request is not None:
            goal = request.goal
            context = request.context
        
        context = context or {}

        trace_id = f"orch-trace::{uuid.uuid4().hex}"
        steps: List[OrchestratorStep] = []
        llm_calls = 0

        start_t = time.perf_counter()
        domain = context.get("domain", "general")

        # 1) 规划阶段（plan）
        plan_prompt = self._build_plan_prompt(goal, context)
        raw_plan = _call_llm(self.llm, plan_prompt)
        llm_calls += 1
        plan = self._parse_plan(raw_plan)

        steps.append(
            OrchestratorStep(
                step_id=f"step::{uuid.uuid4().hex}",
                step_type="plan",
                llm_name=_llm_name(self.llm),
                description="Initial plan generated by main LLM.",
                prompt=plan_prompt,
                raw_output=raw_plan,
                parsed=plan,
            )
        )

        # 2) 执行阶段（execute）
        exec_prompt = self._build_execute_prompt(goal, context, plan)
        raw_exec = _call_llm(self.llm, exec_prompt)
        llm_calls += 1

        steps.append(
            OrchestratorStep(
                step_id=f"step::{uuid.uuid4().hex}",
                step_type="execute",
                llm_name=_llm_name(self.llm),
                description="Execution by main LLM according to the plan.",
                prompt=exec_prompt,
                raw_output=raw_exec,
                parsed=None,
            )
        )

        provisional_output = raw_exec

        # 3) 多模型委员会（可选）
        council_result_dict: Optional[Dict[str, Any]] = None
        if self.council is not None:
            question_for_council = self._build_council_question(
                goal=goal,
                context=context,
                plan=plan,
                provisional_output=provisional_output,
            )
            council_result = self.council.deliberate(
                question=question_for_council,
                context={"domain": domain, "goal": goal, **context},
            )
            council_result_dict = council_result.to_dict()
            steps.append(
                OrchestratorStep(
                    step_id=f"step::{uuid.uuid4().hex}",
                    step_type="council",
                    llm_name="multi-model-council",
                    description="Multi-LLM council deliberation.",
                    prompt=question_for_council,
                    raw_output=council_result_dict,
                    parsed=None,
                )
            )
            final_output = council_result.final_answer or provisional_output
        else:
            final_output = provisional_output

        # 4) 自我反思阶段（reflection）
        reflection = None
        if self.config.enable_reflection:
            reflection_prompt = self._build_reflection_prompt(
                goal=goal,
                context=context,
                plan=plan,
                final_output=final_output,
            )
            raw_reflection = _call_llm(self.llm, reflection_prompt)
            llm_calls += 1

            reflection = {
                "raw_text": raw_reflection,
            }

            steps.append(
                OrchestratorStep(
                    step_id=f"step::{uuid.uuid4().hex}",
                    step_type="reflect",
                    llm_name=_llm_name(self.llm),
                    description="Self-reflection about the task and potential improvements.",
                    prompt=reflection_prompt,
                    raw_output=raw_reflection,
                    parsed=reflection,
                )
            )

        duration = time.perf_counter() - start_t

        execution_summary = {
            "final_output": final_output,
            "goal": goal,
            "domain": domain,
            "plan": plan,
            "council_used": self.council is not None,
            "council_result": council_result_dict,
        }

        top_level_metrics = {
            "latency_sec": duration,
            "llm_calls": llm_calls,
        }

        result = OrchestratorResult(
            trace_id=trace_id,
            status="success",
            steps=steps,
            execution_summary=execution_summary,
            lessons_learned=reflection,
            top_level_metrics=top_level_metrics,
            final_output=final_output,
        )
        return result

    # --------------------------------------------------
    # Prompt 构造
    # --------------------------------------------------
    def _build_plan_prompt(self, goal: str, context: Dict[str, Any]) -> str:
        ctx_json = json.dumps(context, ensure_ascii=False, indent=2)
        return (
            "你是一个通用智能体的 Planner，目标是为一个复杂任务制定清晰、可执行的计划。\n\n"
            "【任务目标】\n"
            f"{goal}\n\n"
            "【上下文】\n"
            f"{ctx_json}\n\n"
            "请你输出一个 JSON 对象，字段包括：\n"
            "  - \"high_level_steps\": 一个字符串列表，每个是一个高层步骤描述。\n"
            "  - \"risks\": 可能的风险点列表（字符串）。\n"
            "  - \"notes\": 其它你认为重要的备注（字符串或字符串列表）。\n"
            "不要输出任何多余文字，只输出 JSON。"
        )

    def _build_execute_prompt(
        self,
        goal: str,
        context: Dict[str, Any],
        plan: Optional[Dict[str, Any]],
    ) -> str:
        ctx_json = json.dumps(context, ensure_ascii=False, indent=2)
        plan_json = json.dumps(plan or {}, ensure_ascii=False, indent=2)
        return (
            "你现在作为一个通用智能体的 Executor，需要根据既定计划给出具体解答或方案。\n\n"
            "【任务目标】\n"
            f"{goal}\n\n"
            "【上下文】\n"
            f"{ctx_json}\n\n"
            "【执行计划（可能为空）】\n"
            f"{plan_json}\n\n"
            "请你直接给出你的完整回答。\n"
            "如果涉及代码，请给出尽量完整的代码片段，并附上简要说明。\n"
            "不要再说你是语言模型，直接进入解决问题。"
        )

    def _build_council_question(
        self,
        *,
        goal: str,
        context: Dict[str, Any],
        plan: Optional[Dict[str, Any]],
        provisional_output: Any,
    ) -> str:
        plan_json = json.dumps(plan or {}, ensure_ascii=False, indent=2)
        ctx_json = json.dumps(context, ensure_ascii=False, indent=2)
        provisional_str = provisional_output if isinstance(provisional_output, str) else json.dumps(
            provisional_output, ensure_ascii=False, indent=2
        )
        return (
            "下面是主模型对一个任务的规划和初步回答，请你们从不同角度进行评审：\n\n"
            "【任务目标】\n"
            f"{goal}\n\n"
            "【上下文】\n"
            f"{ctx_json}\n\n"
            "【主模型的执行计划】\n"
            f"{plan_json}\n\n"
            "【主模型的初步回答】\n"
            f"{provisional_str}\n\n"
            "请重点评估：\n"
            "1. 方案中是否存在明显错误或遗漏。\n"
            "2. 在安全性、风险控制方面是否有重大隐患。\n"
            "3. 是否有显著更好的替代方案。\n"
        )

    def _build_reflection_prompt(
        self,
        *,
        goal: str,
        context: Dict[str, Any],
        plan: Optional[Dict[str, Any]],
        final_output: Any,
    ) -> str:
        ctx_json = json.dumps(context, ensure_ascii=False, indent=2)
        plan_json = json.dumps(plan or {}, ensure_ascii=False, indent=2)
        final_str = final_output if isinstance(final_output, str) else json.dumps(
            final_output, ensure_ascii=False, indent=2
        )
        return (
            "你现在需要对刚刚完成的任务做一次自我反思。\n\n"
            "【任务目标】\n"
            f"{goal}\n\n"
            "【上下文】\n"
            f"{ctx_json}\n\n"
            "【执行计划】\n"
            f"{plan_json}\n\n"
            "【最终输出】\n"
            f"{final_str}\n\n"
            "请你简要回答：\n"
            "1. 这次方案中最可能的薄弱环节是什么？\n"
            "2. 如果再做一次，你会在哪两个方面改进？\n"
            "3. 有哪些可以写入长期记忆（LTS）的稳定经验？\n"
        )

    def _parse_plan(self, raw_plan: str) -> Dict[str, Any]:
        try:
            # Try cleaning json block
            text = raw_plan.strip()
            if "```json" in text:
                text = text.split("```json")[1].split("```")[0].strip()
            elif "```" in text:
                text = text.split("```")[1].strip()
            return json.loads(text)
        except Exception:
            return {"raw_plan": raw_plan, "error": "failed_to_parse_json"}

def _call_llm(llm: Any, prompt: str) -> str:
    """
    统一 LLM 调用接口，兼容多种实现：

    优先：
      - llm.complete(prompt=...)
      - llm.generate(prompt=...)
      - llm(prompt)
    """
    from quentin.llm.context_budget import apply_context_budget
    guarded_prompt, guard = apply_context_budget(prompt_text=prompt)
    if guard.should_block:
        raise ValueError(
            f"context budget blocked: reason={guard.reason} total={guard.total_tokens} window={guard.tokens}"
        )
    if hasattr(llm, "complete"):
        return llm.complete(guarded_prompt)
    if hasattr(llm, "generate"):
        # Adapt to OllamaLLM which expects messages
        try:
             return llm.generate(prompt=guarded_prompt)
        except TypeError:
             return llm.generate(messages=[{"role": "user", "content": guarded_prompt}])
        except Exception:
             pass

    if callable(llm):
        return llm(guarded_prompt)
    raise RuntimeError("LLM client has no complete/generate/callable interface")


def _llm_name(llm: Any) -> str:
    return getattr(llm, "model", getattr(llm, "name", "unknown-llm"))
