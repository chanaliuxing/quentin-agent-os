from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict


KEY_MAP = {
    "strategy_switch_effectiveness": "QUENTIN_VERIFY_STRATEGY_SWITCH_MIN",
    "interrupt_effectiveness": "QUENTIN_VERIFY_INTERRUPT_EFFECTIVENESS_MIN",
    "reset_recovery_rate": "QUENTIN_VERIFY_RESET_RECOVERY_MIN",
    "progress_sync_compliance": "QUENTIN_VERIFY_PROGRESS_SYNC_COMPLIANCE_MIN",
    "attempt_band_coverage": "QUENTIN_VERIFY_ATTEMPT_BAND_COVERAGE_MIN",
}


def _load_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def _pick_bucket(report: Dict[str, Any], bucket: str) -> Dict[str, Any]:
    buckets = report.get("buckets") if isinstance(report.get("buckets"), dict) else {}
    b = str(bucket or "global").strip().lower() or "global"
    chosen = buckets.get(b) if isinstance(buckets.get(b), dict) else None
    if chosen:
        return {"bucket": b, "data": chosen}
    global_data = buckets.get("global") if isinstance(buckets.get("global"), dict) else {}
    return {"bucket": "global", "data": global_data}


def build_env_patch(*, recommendation_report: Dict[str, Any], bucket: str) -> Dict[str, Any]:
    picked = _pick_bucket(recommendation_report, bucket)
    used_bucket = str(picked.get("bucket") or "global")
    data = picked.get("data") if isinstance(picked.get("data"), dict) else {}
    thresholds = data.get("thresholds") if isinstance(data.get("thresholds"), dict) else {}

    lines = [
        "# Auto-generated by scripts/planning_threshold_env_patch.py",
        "# Review before applying to .env",
        f"QUENTIN_VERIFY_AUTOCALIBRATE_DOMAIN_BUCKET={used_bucket}",
    ]
    mapped: Dict[str, float] = {}
    for metric, env_key in KEY_MAP.items():
        if metric not in thresholds:
            continue
        try:
            value = float(thresholds.get(metric))
        except Exception:
            continue
        mapped[env_key] = value
        lines.append(f"{env_key}={value:.3f}")

    return {
        "requested_bucket": str(bucket or "global"),
        "used_bucket": used_bucket,
        "mapped_thresholds": mapped,
        "lines": lines,
    }


def run(*, recommendation_path: Path, output_path: Path, bucket: str) -> Dict[str, Any]:
    report = _load_json(recommendation_path)
    out = build_env_patch(recommendation_report=report, bucket=bucket)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(out["lines"]) + "\n", encoding="utf-8")
    return out


def main() -> int:
    p = argparse.ArgumentParser(description="Generate .env threshold patch from recommendation report")
    p.add_argument("--recommendation", default="generated/benchmarks/planning_threshold_recommendation.json")
    p.add_argument("--output", default="generated/benchmarks/planning_threshold_env_patch.env")
    p.add_argument("--bucket", default="global", help="domain bucket to pick (falls back to global)")
    args = p.parse_args()

    out = run(
        recommendation_path=Path(args.recommendation),
        output_path=Path(args.output),
        bucket=str(args.bucket or "global"),
    )
    print(
        json.dumps(
            {
                "requested_bucket": out.get("requested_bucket"),
                "used_bucket": out.get("used_bucket"),
                "keys": sorted(list((out.get("mapped_thresholds") or {}).keys())),
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
