@app.get("/brain-events/stream")
async def stream_brain_events(
    request: Request,
    session_id: str = "global",
    tenant_id: str = "default",
    after_cursor: str = "",
    dedupe: bool = True,
    use_acked_cursor: bool = False,
    auto_ack: bool = True,
    poll_ms: int = 250,
    timeout_s: float = 10.0,
    max_batches: int = 200,
    max_events: int = 500,
    max_bytes: int = 262144,
    api_key: str = "",
) -> StreamingResponse:
    """
    SSE stream for brain events with cursor replay.
    """
    resolved_sid = _resolve_tenant_session_id(session_id=session_id, tenant_id=tenant_id)
    _enforce_brain_events_access(request, api_key=api_key)
    queue = SystemEventQueue(repo_root=".")
    try:
        _enforce_brain_events_rate_limit(
            f"{tenant_id}:{resolved_sid}",
            queue=queue,
            tenant_id=tenant_id,
            endpoint="stream",
        )
    except BrainEventsRateLimitExceeded as exc:
        retry_after = int(exc.retry_after_sec)
        limit_per_min = int(exc.max_per_min)
        async def _degraded():  # type: ignore[no-untyped-def]
            payload = {
                "session_id": resolved_sid,
                "tenant_id": tenant_id,
                "degraded": True,
                "degrade_reason": "rate_limit",
                "retry_after_sec": retry_after,
                "limit_per_min": limit_per_min,
            }
            yield "event: degraded\n"
            yield f"data: {json.dumps(payload, ensure_ascii=False)}\n\n"
        return StreamingResponse(_degraded(), media_type="text/event-stream")

    async def _gen():  # type: ignore[no-untyped-def]
        cursor = str(after_cursor or "")
        if use_acked_cursor and not cursor:
            cursor = queue.get_acked_cursor(session_id=resolved_sid)
        batches = 0
        waited = 0.0
        step = max(0.05, float(poll_ms) / 1000.0)
        emitted_events = 0
        emitted_bytes = 0
        # initial comment keeps some clients alive
        yield ": brain-events-stream\n\n"
        while batches < max(1, int(max_batches)):
            items = queue.list_brain_events(session_id=resolved_sid, limit=100, after_cursor=cursor, dedupe=dedupe)
            if items:
                for event in items:
                    if emitted_events >= max(1, int(max_events)) or emitted_bytes >= max(1024, int(max_bytes)):
                        meta = {
                            "reason": "backpressure_limit",
                            "session_id": resolved_sid,
                            "tenant_id": tenant_id,
                            "emitted_events": emitted_events,
                            "emitted_bytes": emitted_bytes,
                            "max_events": int(max_events),
                            "max_bytes": int(max_bytes),
                            "cursor": cursor,
                        }
                        yield "event: backpressure\n"
                        yield f"data: {json.dumps(meta, ensure_ascii=False)}\n\n"
                        return
                    payload = event.to_dict()
                    cursor = str(payload.get("cursor") or cursor)
                    encoded = json.dumps(payload, ensure_ascii=False)
                    yield "event: brain_event\n"
                    yield f"data: {encoded}\n\n"
                    emitted_events += 1
                    emitted_bytes += len(encoded.encode("utf-8", errors="ignore"))
                    if auto_ack and cursor:
                        try:
                            queue.ack_cursor(session_id=resolved_sid, cursor=cursor)
                        except Exception:
                            pass
                batches += 1
                waited = 0.0
                continue
            await asyncio.sleep(step)
            waited += step
            if waited >= max(0.1, float(timeout_s)):
                yield "event: heartbeat\n"
                yield f"data: {json.dumps({'session_id': resolved_sid, 'tenant_id': tenant_id, 'cursor': cursor}, ensure_ascii=False)}\n\n"
                break

    return StreamingResponse(_gen(), media_type="text/event-stream")


