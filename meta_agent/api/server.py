def _emit_brain_events_rate_limit_event(
    *,
    queue: Optional[SystemEventQueue],
    session_id: str,
    tenant_id: str,
    endpoint: str,
    retry_after_sec: int,
    max_per_min: int,
    bucket_size: int,
) -> None:
    payload = {
        "reason": "rate_limit",
        "endpoint": str(endpoint or ""),
        "session_id": str(session_id or "global"),
        "tenant_id": str(tenant_id or "default"),
        "retry_after_sec": int(max(1, retry_after_sec)),
        "limit_per_min": int(max(1, max_per_min)),
        "bucket_size": int(max(0, bucket_size)),
    }
    _trace_log_event(event_type="brain_events_rate_limited", payload=payload)
    if queue is None:
        return
    try:
        queue.emit_brain_event(
            session_id=str(session_id or "global"),
            event_type="gateway.rate_limited",
            category="gateway",
            phase="degraded",
            source="meta_agent.api.server",
            payload=payload,
            turn_id="",
        )
    except Exception:
        pass


def _enforce_brain_events_rate_limit(
    session_id: str,
    *,
    queue: Optional[SystemEventQueue] = None,
    tenant_id: str = "default",
    endpoint: str = "",
) -> None:
    raw = str(os.getenv("QUENTIN_BRAIN_EVENTS_RATE_LIMIT_PER_MIN", "240") or "240").strip()
    try:
        max_per_min = max(1, int(raw))
    except Exception:
        max_per_min = 240
    now = time.time()
    bucket = _brain_events_rate_window.setdefault(str(session_id or "global"), [])
    cutoff = now - 60.0
    bucket[:] = [t for t in bucket if t >= cutoff]
    if len(bucket) >= max_per_min:
        oldest = min(bucket) if bucket else now
        retry_after = int(max(1, round((oldest + 60.0) - now)))
        _emit_brain_events_rate_limit_event(
            queue=queue,
            session_id=session_id,
            tenant_id=tenant_id,
            endpoint=endpoint,
            retry_after_sec=retry_after,
            max_per_min=max_per_min,
            bucket_size=len(bucket),
        )
        raise BrainEventsRateLimitExceeded(
            retry_after_sec=retry_after,
            max_per_min=max_per_min,
            bucket_size=len(bucket),
            key=session_id,
        )
    bucket.append(now)


def _clamp_brain_events_limit(limit: int) -> tuple[int, bool]:
    raw = str(os.getenv("QUENTIN_BRAIN_EVENTS_MAX_LIMIT", "200") or "200").strip()
    try:
        max_limit = max(1, int(raw))
    except Exception:
        max_limit = 200
    requested = max(1, int(limit))
    if requested > max_limit:
        return max_limit, True
    return requested, False


def _resolve_tenant_session_id(*, session_id: str, tenant_id: str) -> str:
    sid = str(session_id or "global").strip() or "global"
    tid = str(tenant_id or "default").strip() or "default"
    if tid == "default":
        return sid
    if sid.startswith(f"{tid}:"):
        return sid
    return f"{tid}:{sid}"
