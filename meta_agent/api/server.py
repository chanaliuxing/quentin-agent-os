@app.get("/brain-events/drain")
def drain_brain_events(
    request: Request,
    session_id: str = "global",
    tenant_id: str = "default",
    limit: int = 50,
    after_cursor: str = "",
    dedupe: bool = True,
    use_acked_cursor: bool = False,
    api_key: str = "",
) -> Dict[str, Any]:
    """
    Cursor-based brain event replay API (OpenClaw subscribeEmbeddedPiSession alignment).
    """
    resolved_sid = _resolve_tenant_session_id(session_id=session_id, tenant_id=tenant_id)
    _enforce_brain_events_access(request, api_key=api_key)
    queue = SystemEventQueue(repo_root=".")
    try:
        _enforce_brain_events_rate_limit(
            f"{tenant_id}:{resolved_sid}",
            queue=queue,
            tenant_id=tenant_id,
            endpoint="drain",
        )
    except BrainEventsRateLimitExceeded as exc:
        return {
            "events": [],
            "count": 0,
            "next_cursor": str(after_cursor or ""),
            "session_id": resolved_sid,
            "tenant_id": tenant_id,
            "degraded": True,
            "degrade_reason": "rate_limit",
            "retry_after_sec": int(exc.retry_after_sec),
            "limit_per_min": int(exc.max_per_min),
        }
    safe_limit, backpressure_applied = _clamp_brain_events_limit(limit)
    effective_cursor = str(after_cursor or "").strip()
    if use_acked_cursor and not effective_cursor:
        effective_cursor = queue.get_acked_cursor(session_id=resolved_sid)
    # Replay API is non-destructive; clients advance via cursor/ack.
    events = queue.list_brain_events(
        session_id=resolved_sid,
        limit=safe_limit,
        after_cursor=effective_cursor,
        dedupe=dedupe,
    )
    out = [e.to_dict() for e in events]
    next_cursor = str(out[-1].get("cursor") or "") if out else str(effective_cursor or "")
    return {
        "events": out,
        "count": len(out),
        "next_cursor": next_cursor,
        "session_id": resolved_sid,
        "tenant_id": tenant_id,
        "backpressure_applied": bool(backpressure_applied),
        "effective_limit": int(safe_limit),
    }


