@app.post("/run-task")
async def run_task(req: RunTaskRequest) -> Dict[str, Any]:
    """
    Run a task through the canonical Quentin runtime, serialized per session_id.

    This endpoint intentionally enforces the session lane queue to prevent state races
    when the same session submits multiple tasks concurrently.
    """
    from quentin.bootstrap.container import Container
    from quentin.cognitive.loop import CognitiveTask
    from quentin.infra.concurrency.lane_orchestrator import lane_orchestrator
    from quentin.runtime.tenant_context import TenantContext

    container = Container()
    loop = container.cognitive_loop

    tenant_id = req.tenant_id or "default"
    session_id = req.session_id or "api"

    context = TenantContext(
        tenant_id=tenant_id,
        session_id=session_id,
        domain=req.domain,
        metadata=req.metadata
    )

    task = CognitiveTask(
        input_text=req.input_text,
        task_id=req.task_id or "",
        domain=req.domain,
        environment=req.environment,
        metadata={
            **(req.metadata or {}), 
            **context.to_dict()
        },
    )

    async def _run() -> Any:
        # loop.run_task is synchronous; move it off the event loop.
        return await asyncio.to_thread(loop.run_task, task)

    # P5-A: SLO Enforcement
    if q_feature_flags.slo_governance_v1 and error_budget_controller.is_degradation_required():
        degrade_config = error_budget_controller.get_degradation_mode()
        # Apply degradation: e.g., restrict concurrency or reject high-risk tasks
        if req.domain == "maintenance" and degrade_config.get("disable_high_risk_evolution"):
             return JSONResponse(status_code=503, content={"ok": False, "error": "System in degradation mode: maintenance tasks suspended."})

    try:
        result = await lane_orchestrator.run_in_lane(session_id, _run, tenant_id=tenant_id)
    except RuntimeError as e:
        if "quota exceeded" in str(e).lower():
            return JSONResponse(status_code=429, content={"ok": False, "error": str(e)})
        raise

    _trace_log_event(
        event_type="api_run_task",
        payload={
            "session_id": req.session_id,
            "domain": req.domain,
            "environment": req.environment,
            "task_id": getattr(result, "task_id", None),
            "goal_id": getattr(result, "goal_id", None),
            "done": getattr(result, "done", None),
        },
    )
    # Keep response schema stable and JSON-friendly.
    final_output = getattr(result, "final_output", "") or ""
    try:
        queue = SystemEventQueue(repo_root=".")
        events = queue.list_brain_events(session_id=session_id, limit=400)
        task_turn_id = str(getattr(result, "task_id", "") or "")
        projected = visible_output_from_brain_events(events, turn_id=task_turn_id)
        has_final = has_message_final_brain_event(events, turn_id=task_turn_id)
        if projected or has_final:
            final_output = projected
    except Exception:
        pass

    return {
        "ok": True,
        "task_id": getattr(result, "task_id", None),
        "goal_id": getattr(result, "goal_id", None),
        "done": bool(getattr(result, "done", False)),
        "done_confidence": float(getattr(result, "done_confidence", 0.0) or 0.0),
        "plan_summary": getattr(result, "plan_summary", "") or "",
        "actions_summary": getattr(result, "actions_summary", "") or "",
        "final_output": final_output,
    }


