class BrainEventsRateLimitExceeded(Exception):
    def __init__(self, *, retry_after_sec: int, max_per_min: int, bucket_size: int, key: str) -> None:
        super().__init__("brain events rate limit exceeded")
        self.retry_after_sec = int(max(1, retry_after_sec))
        self.max_per_min = int(max(1, max_per_min))
        self.bucket_size = int(max(0, bucket_size))
        self.key = str(key or "global")


def _trace_log_event(*, event_type: str, payload: Dict[str, Any]) -> None:
    try:
        fn = getattr(trace_recorder, "log_event", None)
        if callable(fn):
            fn(event_type=event_type, payload=payload)
        return
    except Exception:
        pass

