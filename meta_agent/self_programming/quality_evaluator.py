"""
Code Quality Evaluator for Self-Programming Engine.

Evaluates generated code patches for quality metrics:
- Syntax validity
- Complexity (using radon)
- Code style (basic heuristics)
- Test pass rate (if tests exist)
"""
from __future__ import annotations

import ast
import json
import logging
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Any, Optional

logger = logging.getLogger(__name__)


@dataclass
class QualityMetrics:
    """Quality metrics for generated code."""
    syntax_valid: bool
    complexity_score: float  # 0.0 (worst) to 1.0 (best)
    style_score: float  # 0.0 (worst) to 1.0 (best)
    test_pass_rate: Optional[float]  # 0.0 to 1.0, None if no tests
    overall_score: float  # Weighted average
    details: Dict[str, Any]  # Additional metrics


class CodeQualityEvaluator:
    """
    Evaluates code quality for patches generated by self-programming engine.

    Uses:
    - ast.parse() for syntax checking
    - radon for cyclomatic complexity
    - Basic heuristics for style (docstrings, type hints)
    """

    def __init__(
        self,
        *,
        complexity_weight: float = 0.3,
        style_weight: float = 0.3,
        syntax_weight: float = 0.2,
        test_weight: float = 0.2,
        max_acceptable_complexity: int = 10,
    ):
        self.complexity_weight = complexity_weight
        self.style_weight = style_weight
        self.syntax_weight = syntax_weight
        self.test_weight = test_weight
        self.max_acceptable_complexity = max_acceptable_complexity

    def evaluate_file(self, file_path: Path) -> QualityMetrics:
        """
        Evaluate a single Python file.

        Args:
            file_path: Path to the Python file

        Returns:
            QualityMetrics with scores
        """
        if not file_path.exists():
            logger.warning("File not found: %s", file_path)
            return self._failed_metrics(f"File not found: {file_path}")

        try:
            code = file_path.read_text()
        except Exception as e:
            logger.exception("Failed to read file: %s", file_path)
            return self._failed_metrics(f"Read error: {e}")

        return self.evaluate_code(code, file_path=str(file_path))

    def evaluate_code(self, code: str, file_path: Optional[str] = None) -> QualityMetrics:
        """
        Evaluate code snippet for quality.

        Args:
            code: Python source code
            file_path: Optional file path for context

        Returns:
            QualityMetrics with scores
        """
        details: Dict[str, Any] = {}

        # 1. Check syntax
        syntax_valid, syntax_error = self._check_syntax(code)
        syntax_score = 1.0 if syntax_valid else 0.0

        if not syntax_valid:
            logger.warning("Syntax error in %s: %s", file_path or "code", syntax_error)
            details["syntax_error"] = syntax_error
            return QualityMetrics(
                syntax_valid=False,
                complexity_score=0.0,
                style_score=0.0,
                test_pass_rate=None,
                overall_score=0.0,
                details=details,
            )

        # 2. Assess complexity
        complexity_score, complexity_details = self._assess_complexity(code, file_path)
        details.update(complexity_details)

        # 3. Assess style
        style_score, style_details = self._assess_style(code)
        details.update(style_details)

        # 4. Test pass rate (optional, requires running tests)
        test_pass_rate = None  # Will be set externally by engine

        # Calculate overall score
        overall_score = self._calculate_overall_score(
            syntax_score=syntax_score,
            complexity_score=complexity_score,
            style_score=style_score,
            test_pass_rate=test_pass_rate,
        )

        return QualityMetrics(
            syntax_valid=syntax_valid,
            complexity_score=complexity_score,
            style_score=style_score,
            test_pass_rate=test_pass_rate,
            overall_score=overall_score,
            details=details,
        )

    def _check_syntax(self, code: str) -> tuple[bool, Optional[str]]:
        """Check if code has valid Python syntax."""
        try:
            ast.parse(code)
            return True, None
        except SyntaxError as e:
            return False, f"Line {e.lineno}: {e.msg}"
        except Exception as e:
            return False, str(e)

    def _assess_complexity(
        self, code: str, file_path: Optional[str]
    ) -> tuple[float, Dict[str, Any]]:
        """
        Assess cyclomatic complexity using radon.

        Returns:
            (score, details) where score is 0.0 (complex) to 1.0 (simple)
        """
        try:
            # Use radon to get complexity
            result = subprocess.run(
                ["radon", "cc", "-s", "-a", "-j", "-"],
                input=code,
                capture_output=True,
                text=True,
                timeout=5,
            )

            if result.returncode != 0:
                logger.warning("radon failed: %s", result.stderr)
                return 0.5, {"radon_error": result.stderr}

            complexity_data = json.loads(result.stdout)

            # complexity_data is like: {"stdin": [{"complexity": 5, ...}, ...]}
            functions = complexity_data.get("stdin", []) or complexity_data.get("-", [])
            if not functions:
                # No functions found, default to good score
                return 1.0, {"avg_complexity": 1.0, "max_complexity": 1.0}

            complexities = [f.get("complexity", 0) for f in functions if isinstance(f, dict)]
            if not complexities:
                return 1.0, {"avg_complexity": 1.0}

            avg_complexity = sum(complexities) / len(complexities)
            max_complexity = max(complexities)

            # Score: 1.0 if all functions <= max_acceptable, 0.0 if avg > 2*max_acceptable
            # Linear interpolation in between
            if avg_complexity <= self.max_acceptable_complexity:
                score = 1.0
            elif avg_complexity >= self.max_acceptable_complexity * 2:
                score = 0.0
            else:
                # Linear decay from 1.0 to 0.0
                score = 1.0 - (avg_complexity - self.max_acceptable_complexity) / self.max_acceptable_complexity

            return score, {
                "avg_complexity": avg_complexity,
                "max_complexity": max_complexity,
                "num_functions": len(complexities),
            }

        except subprocess.TimeoutExpired:
            logger.warning("radon timed out for %s", file_path or "code")
            return 0.5, {"radon_timeout": True}
        except json.JSONDecodeError:
            logger.warning("radon output not valid JSON for %s", file_path or "code")
            return 0.5, {"radon_json_error": True}
        except Exception as e:
            logger.exception("Failed to assess complexity")
            return 0.5, {"radon_exception": str(e)}

    def _assess_style(self, code: str) -> tuple[float, Dict[str, Any]]:
        """
        Assess code style using basic heuristics.

        Checks for:
        - Docstrings
        - Type hints
        - Descriptive variable names
        - Blank line usage
        """
        details: Dict[str, Any] = {}

        # Check for docstrings
        has_docstring = '"""' in code or "'''" in code
        details["has_docstring"] = has_docstring

        # Check for type hints
        has_type_hints = ("->" in code and ":" in code) or "def " in code and ":" in code.split("def ")[1].split(")")[0]
        details["has_type_hints"] = has_type_hints

        # Check for descriptive names (not single letters, except common ones)
        lines = code.split("\n")
        function_defs = [l for l in lines if l.strip().startswith("def ")]
        has_descriptive_names = all(
            len(line.split("def ")[1].split("(")[0].strip()) > 2 or
            line.split("def ")[1].split("(")[0].strip() in ["f", "x", "y", "i", "j", "k"]
            for line in function_defs
        ) if function_defs else True
        details["has_descriptive_names"] = has_descriptive_names

        # Check for blank lines (spacing)
        blank_lines = sum(1 for l in lines if not l.strip())
        total_lines = len(lines)
        has_spacing = (blank_lines / total_lines) > 0.05 if total_lines > 0 else False
        details["has_spacing"] = has_spacing

        # Calculate style score
        doc_score = 1.0 if has_docstring else 0.0
        hints_score = 1.0 if has_type_hints else 0.5  # Some tolerance
        names_score = 1.0 if has_descriptive_names else 0.7
        spacing_score = 1.0 if has_spacing else 0.8

        style_score = (doc_score * 0.4) + (hints_score * 0.3) + (names_score * 0.2) + (spacing_score * 0.1)

        details["style_score_breakdown"] = {
            "docstring": doc_score,
            "type_hints": hints_score,
            "names": names_score,
            "spacing": spacing_score,
        }

        return style_score, details

    def _calculate_overall_score(
        self,
        syntax_score: float,
        complexity_score: float,
        style_score: float,
        test_pass_rate: Optional[float],
    ) -> float:
        """
        Calculate weighted overall quality score.

        If test_pass_rate is None, redistribute its weight to other scores.
        """
        if test_pass_rate is None:
            # Redistribute test weight
            total_weight = self.syntax_weight + self.complexity_weight + self.style_weight
            adjusted_syntax_weight = self.syntax_weight / total_weight
            adjusted_complexity_weight = self.complexity_weight / total_weight
            adjusted_style_weight = self.style_weight / total_weight

            return (
                syntax_score * adjusted_syntax_weight +
                complexity_score * adjusted_complexity_weight +
                style_score * adjusted_style_weight
            )
        else:
            return (
                syntax_score * self.syntax_weight +
                complexity_score * self.complexity_weight +
                style_score * self.style_weight +
                test_pass_rate * self.test_weight
            )

    def _failed_metrics(self, reason: str) -> QualityMetrics:
        """Return failed metrics."""
        return QualityMetrics(
            syntax_valid=False,
            complexity_score=0.0,
            style_score=0.0,
            test_pass_rate=None,
            overall_score=0.0,
            details={"error": reason},
        )
