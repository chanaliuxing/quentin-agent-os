# meta_agent/tools/coder/gemini_cli_backend.py
import os
import shlex
import subprocess
import shutil
from meta_agent.tools.coder.base import (
    CoderBackend,
    CodeGenerationRequest,
    CodeGenerationResult,
)


class GeminiCliBackend(CoderBackend):
    name = "gemini_cli"

    def __init__(self, cmd: str | None = None):
        # Allow overriding via GEMINI_CLI_CMD to match local binary name (e.g., "gemini-cli")
        raw_cmd = cmd or os.environ.get("GEMINI_CLI_CMD", "gemini")
        self.cmd = shlex.split(raw_cmd)
        self.available = shutil.which(self.cmd[0]) is not None

    def generate(self, req: CodeGenerationRequest) -> CodeGenerationResult:
        if not self.available:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning="gemini cli not available on PATH",
            )
        prompt = self._build_prompt(req)
        cmd = self.cmd + ["--prompt", prompt, "--approval-mode", "yolo"]
        env = os.environ.copy()
        env["CI"] = "true"
        env["NON_INTERACTIVE"] = "1"
        env.setdefault("TERM", "dumb")
        try:
            proc = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                check=False,
                env=env,
            )
        except Exception as e:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"gemini cli error: {e}",
            )

        if proc.returncode != 0:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"gemini cli non-zero exit ({proc.returncode}): {proc.stderr}",
                raw_output=proc.stdout,
            )

        output = proc.stdout.strip()
        return CodeGenerationResult(
            success=True,
            code=output,
            reasoning="generated by gemini cli",
            raw_output=output,
        )

    def _build_prompt(self, req: CodeGenerationRequest) -> str:
        from pathlib import Path
        ctx = []
        for path in req.context_files:
            p = Path(path)
            if not p.exists():
                continue
            try:
                text = p.read_text(encoding="utf-8")
            except Exception:
                continue
            ctx.append(f"=== FILE: {path} ===\n{text}\n")

        ctx_block = "\n\n".join(ctx)
        prompt = f"""
You are a highly skilled coding assistant.

Goal:
{req.goal}

Context files provided:
{ctx_block}

Specific Instructions:
{req.instructions}

Important: Output ONLY the improved/new code. Do not include markdown blocks unless they are part of the file content. Adhere to project conventions.
"""
        return prompt.strip()
