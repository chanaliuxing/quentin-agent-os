import os
import shlex
import shutil
import subprocess

from meta_agent.tools.coder.base import (
    CoderBackend,
    CodeGenerationRequest,
    CodeGenerationResult,
)


class ClaudeCodeCliBackend(CoderBackend):
    name = "claude_code_cli"

    def __init__(self, cmd: str | None = None):
        raw_cmd = cmd or os.environ.get("CLAUDE_CODE_CLI_CMD", "claude")
        self.cmd = shlex.split(raw_cmd)
        self.available = shutil.which(self.cmd[0]) is not None

    def generate(self, req: CodeGenerationRequest) -> CodeGenerationResult:
        if not self.available:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning="claude code cli not available on PATH",
            )

        prompt = self._build_prompt(req)
        cmd = self.cmd + ["-p", prompt]
        env = os.environ.copy()
        env["CI"] = "true"
        env["NON_INTERACTIVE"] = "1"
        env.setdefault("TERM", "dumb")
        try:
            proc = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                check=False,
                env=env,
            )
        except Exception as e:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"claude code cli error: {e}",
            )

        if proc.returncode != 0:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"claude code cli non-zero exit ({proc.returncode}): {proc.stderr}",
                raw_output=proc.stdout,
            )

        output = proc.stdout.strip()
        return CodeGenerationResult(
            success=True,
            code=output,
            reasoning="generated by claude code cli",
            raw_output=output,
        )

    def _build_prompt(self, req: CodeGenerationRequest) -> str:
        from pathlib import Path
        ctx = []
        for path in req.context_files:
            p = Path(path)
            if not p.exists():
                continue
            try:
                text = p.read_text(encoding="utf-8")
            except Exception:
                continue
            ctx.append(f"=== FILE: {path} ===\n{text}\n")

        ctx_block = "\n\n".join(ctx)
        prompt = f"""
Goal:
{req.goal}

Context:
{ctx_block}

Instructions:
{req.instructions}

Please output the completed code.
"""
        return prompt.strip()
