# meta_agent/tools/coder/codex_cli_backend.py
import os
import shlex
import subprocess
import json
from typing import List
from pathlib import Path
import shutil

from meta_agent.tools.coder.base import (
    CoderBackend,
    CodeGenerationRequest,
    CodeGenerationResult,
)


class CodexCliBackend(CoderBackend):
    name = "codex_cli"

    def __init__(self, cmd: str | None = None):
        # Allow overriding via CODEX_CLI_CMD to match local binary name (e.g., "codex-cli")
        raw_cmd = cmd or os.environ.get("CODEX_CLI_CMD", "codex")
        self.cmd = shlex.split(raw_cmd)
        self.available = shutil.which(self.cmd[0]) is not None

    def generate(self, req: CodeGenerationRequest) -> CodeGenerationResult:
        prompt = self._build_prompt(req)
        cmd = self.cmd + ["generate", "--prompt", prompt, "--lang", req.preferred_language]
        if not self.available:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning="codex cli not available on PATH",
            )
        env = os.environ.copy()
        env["CI"] = "true"
        env["NON_INTERACTIVE"] = "1"
        env.setdefault("TERM", "dumb")
        try:
            proc = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                check=False,
                env=env,
            )
        except Exception as e:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"codex cli error: {e}",
            )

        if proc.returncode != 0:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"codex cli non-zero exit ({proc.returncode}): {proc.stderr}",
                raw_output=proc.stdout,
            )

        # 你自己的 codex cli 输出格式可能是纯文本/JSON，下面只是一个示例：
        output = proc.stdout.strip()
        return CodeGenerationResult(
            success=True,
            code=output,
            reasoning="generated by codex cli",
            raw_output=output,
        )

    def _build_prompt(self, req: CodeGenerationRequest) -> str:
        ctx = []
        for path in req.context_files:
            p = Path(path)
            if not p.exists():
                continue
            try:
                text = p.read_text(encoding="utf-8")
            except Exception:
                continue
            ctx.append(f"=== FILE: {path} ===\n{text}\n")

        ctx_block = "\n\n".join(ctx)
        prompt = f"""
You are a coding assistant.

Goal:
{req.goal}

Context files:
{ctx_block}

Instructions:
{req.instructions}

Please output ONLY the code for the target file or diff, without extra commentary.
"""
        return prompt.strip()
