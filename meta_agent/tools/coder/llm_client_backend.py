# meta_agent/tools/coder/llm_client_backend.py
from __future__ import annotations
import os
import logging
from typing import Optional

from meta_agent.tools.coder.base import (
    CoderBackend,
    CodeGenerationRequest,
    CodeGenerationResult,
)
from quentin.llm.client import call_llm

logger = logging.getLogger(__name__)

class LLMClientCoderBackend(CoderBackend):
    """
    Coder backend that uses the unified quentin.llm.client.call_llm.
    Supports gemini, openai, claude, kimi, qwen, etc. via environment variables.
    """
    name = "llm_client"

    def generate(self, req: CodeGenerationRequest) -> CodeGenerationResult:
        # Configuration from environment
        provider = os.getenv("CODER_LLM_PROVIDER", os.getenv("LLM_PROVIDER", "gemini")).strip().lower()
        model = os.getenv("CODER_LLM_MODEL", os.getenv("LLM_MODEL", "gemini-2.0-flash")).strip()
        
        # Build prompt
        full_prompt = f"Goal: {req.goal}\n\nInstructions: {req.instructions}"
        
        try:
            output = call_llm(
                config=model,
                user_prompt=full_prompt,
                system_prompt="You are a senior software engineer assistant specialized in self-programming. Output code patches according to instructions.",
                provider=provider,
                actor="coder_llm_client",
                domain="core",
                environment="sandbox",
                risk_level="high",
                action_metadata={
                    "topic": "self_programming_generation",
                    "goal": req.goal[:200]
                }
            )
            
            return CodeGenerationResult(
                success=True,
                code=output,
                reasoning=f"generated by {provider}:{model}",
                raw_output=output,
            )
        except Exception as e:
            logger.exception("LLMClientCoderBackend generation failed")
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"Error calling {provider}:{model}: {e}",
            )