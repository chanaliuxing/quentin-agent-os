import os
from meta_agent.tools.coder.base import (
    CoderBackend,
    CodeGenerationRequest,
    CodeGenerationResult,
)
from meta_agent.llm.ollama_client import OllamaClient
from meta_agent.llm.client import LLMRequest

class OllamaCoderBackend(CoderBackend):
    name = "ollama"

    def __init__(self):
        self.client = OllamaClient()
        self.model = os.getenv("LLM_MODEL", "qwen3-vl:latest")
        self.available = True

    def generate(self, req: CodeGenerationRequest) -> CodeGenerationResult:
        prompt = f"""
Goal: {req.goal}

Instructions:
{req.instructions}

Please provide the implementation code and verification test code in a single valid JSON object with keys 'implementation_code' and 'verification_test_code'.
Wrap the JSON object in a markdown code block (```json).
IMPORTANT: Ensure all newlines and quotes within the code strings are properly escaped for JSON.
Example:
```json
{{
  "implementation_code": "def hello():\\n    print('Hello')",
  "verification_test_code": "def test_hello():\\n    assert True"
}}
```
"""
        try:
            response = self.client.generate(
                LLMRequest(
                    model=self.model,
                    prompt=prompt,
                    temperature=0.2,
                    max_tokens=4000
                )
            )
            return CodeGenerationResult(
                success=True,
                code=response,
                reasoning="Generated by Ollama",
                raw_output=response
            )
        except Exception as e:
            return CodeGenerationResult(
                success=False,
                code="",
                reasoning=f"Ollama error: {e}"
            )
